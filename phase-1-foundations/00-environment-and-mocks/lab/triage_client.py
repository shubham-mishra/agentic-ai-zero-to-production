SeverityLevel = Literal["P1", "P2", "P3"]


class IncidentAlert(BaseModel):
    """Schema representing an incoming infrastructure incident alert."""

    incident_id: str = Field(..., description="Unique incident alert identifier")
    service: str = Field(..., description="Affected infrastructure service or microservice")
    severity: SeverityLevel = Field(..., description="Reported alert severity level")
    message: str = Field(..., description="Raw log excerpt or incident alert description")
    timestamp: str | None = Field(default=None, description="ISO8601 timestamp of incident detection")


class TriageDecision(BaseModel):
    """Deterministic structured output generated by the triage reasoning loop."""

    incident_id: str = Field(..., description="Reference incident alert identifier")
    severity: SeverityLevel = Field(..., description="Assessed severity level (P1, P2, or P3)")
    root_cause_hypothesis: str = Field(..., description="Concise engineering hypothesis for the incident root cause")
    recommended_action: str = Field(..., description="Direct technical remediation or triage action step")
    automated_remediation_allowed: bool = Field(
        ...,
        description="Whether automated scripts are authorized to execute remediation without human intervention",
    )


class TriageExecutionMetadata(BaseModel):
    """Operational metrics captured during live model inference."""

    latency_ms: float = Field(..., description="Inference network roundtrip duration in milliseconds")
    prompt_tokens: int = Field(..., description="Tokens consumed by prompt instructions and input")
    completion_tokens: int = Field(..., description="Tokens generated in the structured completion")
    total_tokens: int = Field(..., description="Total token consumption for this triage query")
    model: str = Field(..., description="Name of the model that executed inference")


class TriageResult(BaseModel):
    """Complete triage payload combining structured decision and operational telemetry."""

