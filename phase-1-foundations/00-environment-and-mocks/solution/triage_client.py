"""Enterprise Incident Triage Gateway Client.

Connects directly to frontier model APIs to perform deterministic incident triage,
enforcing strict Pydantic output schemas, latency tracking, and token accounting.
"""

from __future__ import annotations

import json
import os
import time
from typing import Any, Literal, Optional
from dotenv import load_dotenv
from openai import OpenAI
from pydantic import BaseModel, Field

load_dotenv()

SeverityLevel = Literal["P1", "P2", "P3"]


class IncidentAlert(BaseModel):
    """Schema representing an incoming infrastructure incident alert."""

    incident_id: str = Field(..., description="Unique incident alert identifier")
    service: str = Field(..., description="Affected infrastructure service or microservice")
    severity: SeverityLevel = Field(..., description="Reported alert severity level")
    message: str = Field(..., description="Raw log excerpt or incident alert description")
    timestamp: str | None = Field(default=None, description="ISO8601 timestamp of incident detection")


class TriageDecision(BaseModel):
    """Deterministic structured output generated by the triage reasoning loop."""

    incident_id: str = Field(..., description="Reference incident alert identifier")
    severity: SeverityLevel = Field(..., description="Assessed severity level (P1, P2, or P3)")
    root_cause_hypothesis: str = Field(..., description="Concise engineering hypothesis for the incident root cause")
    recommended_action: str = Field(..., description="Direct technical remediation or triage action step")
    automated_remediation_allowed: bool = Field(
        ...,
        description="Whether automated scripts are authorized to execute remediation without human intervention",
    )


class TriageExecutionMetadata(BaseModel):
    """Operational metrics captured during live model inference."""

    latency_ms: float = Field(..., description="Inference network roundtrip duration in milliseconds")
    prompt_tokens: int = Field(..., description="Tokens consumed by prompt instructions and input")
    completion_tokens: int = Field(..., description="Tokens generated in the structured completion")
    total_tokens: int = Field(..., description="Total token consumption for this triage query")
    model: str = Field(..., description="Name of the model that executed inference")


class TriageResult(BaseModel):
    """Complete triage payload combining structured decision and operational telemetry."""

    decision: TriageDecision
    metadata: TriageExecutionMetadata


class TriageClient:
    """Production client executing incident triage workflows against frontier LLMs."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        client: Optional[OpenAI] = None,
    ) -> None:
        """Initialize the triage client with credentials and target model configuration."""
        self.api_key = api_key or os.getenv("OPENAI_API_KEY")
        self.model = model or os.getenv("OPENAI_MODEL", "gpt-4o-mini")

        if client is not None:
            self.client = client
        else:
            if not self.api_key:
                raise ValueError("OPENAI_API_KEY must be provided via argument or root .env file.")
            self.client = OpenAI(api_key=self.api_key)

    def _build_system_prompt(self) -> str:
        """Construct the deterministic system operating manual for incident triage."""
        return (
            "You are an expert Enterprise Incident Triage Agent. "
            "Analyze the incoming infrastructure alert and provide a deterministic triage decision. "
            "Follow these hard rules:\n"
            "1. Output valid JSON matching the TriageDecision schema.\n"
            "2. Severity P1 represents critical service outages or severe data corruption.\n"
            "3. Severity P2 represents degraded performance, high error spikes, or elevated latency.\n"
            "4. Severity P3 represents non-critical warnings or single-node minor anomalies.\n"
            "5. automated_remediation_allowed is TRUE ONLY for P2 or P3 non-destructive remediation (e.g. cache flush, restart).\n"
            "6. automated_remediation_allowed is FALSE for all P1 incidents or destructive changes."
        )

    def _build_user_prompt(self, alert: IncidentAlert) -> str:
        """Serialize alert data into the prompt."""
        return f"<incident_alert>\n{alert.model_dump_json(indent=2)}\n</incident_alert>"

    def triage_incident(self, alert: IncidentAlert) -> TriageResult:
        """Execute structured triage for the supplied alert against the live model.

        Args:
            alert: Validated infrastructure incident alert.

        Returns:
            TriageResult containing validated decision and execution metadata.
        """
        system_prompt = self._build_system_prompt()
        user_prompt = self._build_user_prompt(alert)

        start_time = time.perf_counter()

        try:
            # Execute structured output parsing via OpenAI SDK
            completion = self.client.beta.chat.completions.parse(
                model=self.model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                response_format=TriageDecision,
            )
            duration_ms = (time.perf_counter() - start_time) * 1000.0

            parsed_decision = completion.choices[0].message.parsed
            if parsed_decision is None:
                raw_content = completion.choices[0].message.content or "{}"
                parsed_decision = TriageDecision.model_validate_json(raw_content)

            usage = completion.usage
            metadata = TriageExecutionMetadata(
                latency_ms=round(duration_ms, 2),
                prompt_tokens=usage.prompt_tokens if usage else 0,
                completion_tokens=usage.completion_tokens if usage else 0,
                total_tokens=usage.total_tokens if usage else 0,
                model=completion.model,
            )

        except Exception as exc:
            # Fallback for models or endpoints requiring standard json_object mode
            try:
                response = self.client.chat.completions.create(
                    model=self.model,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    response_format={"type": "json_object"},
                )
                duration_ms = (time.perf_counter() - start_time) * 1000.0
                content = response.choices[0].message.content or "{}"
                parsed_decision = TriageDecision.model_validate_json(content)

                usage = response.usage
                metadata = TriageExecutionMetadata(
                    latency_ms=round(duration_ms, 2),
                    prompt_tokens=usage.prompt_tokens if usage else 0,
                    completion_tokens=usage.completion_tokens if usage else 0,
                    total_tokens=usage.total_tokens if usage else 0,
                    model=response.model,
                )
            except Exception:
                raise exc

        # Deterministic business invariant: P1 alerts must never permit unattended automated remediation
        if parsed_decision.severity == "P1":
            parsed_decision.automated_remediation_allowed = False

        return TriageResult(decision=parsed_decision, metadata=metadata)
